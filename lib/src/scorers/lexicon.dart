final Set<String> _entries = {
  for (final w in kCommonTamil) normalizeForMatch(w),
};

/// True when [word] is a common word or a common stem with an ending.
bool isCommonWord(String word) {
  final w = normalizeForMatch(word);
  if (_entries.contains(w)) return true;
  final runes = w.runes.length;
  for (final e in _entries) {
    final stem = e.runes.length;
    if (stem >= _minStemRunes &&
        runes - stem <= _maxSuffixRunes &&
        w.startsWith(e)) {
      return true;
    }
  }
  return false;
}

/// Share of [ws] that are common words, from 0 to 1; 0 for no words.
double commonWordRatio(List<String> ws) =>
    ws.isEmpty ? 0 : ws.where(isCommonWord).length / ws.length;
