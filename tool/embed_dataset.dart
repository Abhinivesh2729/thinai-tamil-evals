import 'dart:io';

/// Writes `lib/src/data/ta_v1.g.dart` from `data/ta/v1.json`.
///
/// The JSON is the source contributors edit. It is embedded as a Dart string
/// so the package stays pure Dart: a Flutter app, a CLI and a test all load
/// the same bytes without asset bundles or file paths. `test/dataset_test.dart`
/// fails when the two drift apart.
///
///     dart run tool/embed_dataset.dart
void main() {
  final json = File('data/ta/v1.json').readAsStringSync();
  File('lib/src/data/ta_v1.g.dart').writeAsStringSync(render(json));
  stdout.writeln('wrote lib/src/data/ta_v1.g.dart');
}

String render(String json) =>
    '// GENERATED by tool/embed_dataset.dart from data/ta/v1.json. Do not edit.\n'
    '\n'
    '/// The Tamil dataset, version 1, as JSON.\n'
    "const kTamilV1Json = r'''\n$json''';\n";
